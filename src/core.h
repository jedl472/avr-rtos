/**
 * @file Core.h
 * @brief Main file containing core functions for the kernel.
 * 
 * This file contains code for tick ISR, tasks, error handling, and some useful macros.
 *
 */

#ifndef CORE_H
#define CORE_H

#include <stdint.h>
#include <stddef.h>

#include <avr/io.h>
#include <avr/interrupt.h>

#include "debug.h"
#include "config.h"

/**
 * @name Critical section macros.
 * @brief Macros for entering kernel critical sections.
 *
 * Macros that should enclose all writes to memory used by the kernel or shared between tasks (like queues).
 * Currently they save and return SREG and disable interrupts.
 * @{
 */
#define coreENTER_CRITICAL() uint8_t _sreg = SREG; asm volatile("cli")
#define coreEXIT_CRITICAL() SREG = _sreg
/** @} */

/** 
 * @brief Macro to supress -Wunused-parameter warning.
 */
#define UNUSED(x) (void)(x) // to supress -Wunused-parameter with creating tasks

/**
 * @brief Minimum stack size for a task, represented in bytes.
 *
 * Currently when preforming a context switch, scheduler() saves everything onto the previous running task stack. 
 * This means, that every task has to currently allocate a huge amount of unused space to support context switching, specified by this value.
 * Currently this value was generated by a guess with a giant safety margin.
 * @todo find this value out for real, by creating a separate stact for scheduler() and mesuring stack footpring of a idle task
 */
#define coreMINIMUM_STACK_SIZE 128

/**
 * @brief Priority of the idle task.
 *
 * This value should be set to a sufficiently high number, no task should have a lower priority than this.
 */
#define coreIDLE_TASK_PRIORITY 127

/**
 * @brief Arbitrary value chosen used as stack canary.
 *
 * This value is saved at the end of task stack at its creation, and is checked on each context switch. If it's not equal to this, the kernel panics with STACK_OVERFLOW.
 */
#define coreSTACK_CANARY_VALUE 0x67

/**
 * @brief Type representing task priority.
 *
 * Signed, because I felt like negative task priority might be useful.
 */
typedef int8_t task_priority_t;

/**
 * @brief Type used for tick counting, mainly when suspending tasks.
 */
typedef uint16_t tick_counter_t;

/**
 * @brief Ticks elapsed from os_start.
 *
 * This variable is incremented in the tick ISR, and because that can be supressed by coreENTER_CRITICAL, value of this should be used for kernel debugging only.
 *
 * @todo this should not be exposed, or not be used at all.
 */
extern tick_counter_t os_ticks;

/** 
 * @brief Interface-like struct for waking up tasks.
 *
 * Each tcb has a pointer to this flag, which gets checkeb by the scheduler. If the task is in BLOCKED state and this flag is not equal to zero, task gets set to READY state.
 * This flag is not cleared by the scheduler after waking up tasks, so that should be handled by the tasks or the event structures.
 * 
 * Defined as a struct because I felt like more parameters can be useful in the future.
 */
typedef struct flag {
    uint8_t *count;
} flag_t;

// State of infividual tasks used by the schedulerl.
typedef enum task_state {
    RUNNING,    // currently running
    READY,      // ready to run
    SUSPENDED,  // sleeping for ticks, gets woken up by the scheduler
    BLOCKED,    // waiting for an event, gets woken up by an event
    FINISHED    // effectivelly marked for deletion, unused
} task_state_t;

/** 
 * @brief Task Control Block struct holding information about each task.
 *
 * @todo move into the source file
 */
typedef struct tcb {
    uint8_t *sp;                ///< Stack pointer of the task.
    task_state_t state;         ///< State of the task.
    uint8_t id;                 ///< Id of the task. @todo is unused
    task_priority_t priority;   ///< priority of the task
    
    tick_counter_t ticks_remaining_suspended;   ///< ticks of sleep remaining for SUSPENDED tasks
    flag_t *waiting_on_flag;                    ///< flag used by the scheduler to wake BLOCKED tasks 

    uint16_t stack_size;        ///< @todo damn I forgot what this was for 
    uint8_t *stack_base;        ///< @todo damn I forgot what this was for 


} tcb_t;

/**
 * @brief Pointer to the tcb of the currently running task. 
 *
 * Is exposed because some functions in debug.c use it.
 *
 * @todo unexpose or add a getter function.
 */
extern volatile tcb_t *current_tcb;

/**
 * @brief Yields the current task and calls the scheduler.
 */
__attribute__((naked)) void task_yield(void);

void task_create(tcb_t *t, task_priority_t priority, uint8_t *stack, 
                    uint16_t size, void (*fn)(void *), void *arg);

/**
 * @brief Suspends currently running taks for a number of OS ticks.
 *
 * Currently not very real time, because critical sections can mess with the way how ticks are counter (by supressing TICK isr);
 * @todo rewrite it to use a different timer
 */
void task_suspend_ticks(tick_counter_t ticks);

void os_start(void);

void debug_register_task(tcb_t *task, uint8_t pos);

void task_register(tcb_t *tcb);

/**
 * @brief Array of registered_tasks.
 *
 * @todo exposed for debug only.
 */
extern tcb_t *registered_tasks[configMAX_TASKS];  // TODO remove

typedef enum kp_type {
    //core errors
    STACK_OVERFLOW, // TODO
    EXCEEDED_MAX_TASKS, // user error - means user tried to register more tasks than configMAX_TASKS
    CORRUPTED_IDLE_TASK, // kernel error - means scheduler did not find suitable task to run

    //queue errors
    QUEUE_OVERFLOW, // user error - tried to queue_add on a full queue
    POP_ON_EMPTY_QUEUE // kernel error - called queue_pop on an empty queue
} kp_type_t;

void throw_kp(kp_type_t kp_type);

#endif // !CORE_H

